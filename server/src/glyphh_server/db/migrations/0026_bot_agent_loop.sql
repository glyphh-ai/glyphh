-- A bot is a Claude agent you talk to (docs/specs/bot-agent-loop.md): its run is one Claude Agent SDK turn, no longer
-- a loop of steps. A bot gains its standing task (what it does when it runs on its own), its example prompts, its
-- role (one orchestrator per org, never deleted) and its spec as it was before (old_spec: the way back; nothing reads
-- it). Its plugins (a template's package, kept at the version installed) are bot_plugins; a waiting run's session,
-- mirrored from the Agent SDK so an answer carries on after a restart, is bot_sessions. The bots themselves are
-- converted by ops/bots/converted.py, which the schema step runs after the migrations.
ALTER TABLE bots ADD COLUMN IF NOT EXISTS role TEXT DEFAULT 'bot' NOT NULL;
ALTER TABLE bots ADD COLUMN IF NOT EXISTS task TEXT DEFAULT '' NOT NULL;
ALTER TABLE bots ADD COLUMN IF NOT EXISTS examples JSONB DEFAULT '[]'::jsonb NOT NULL;
ALTER TABLE bots ADD COLUMN IF NOT EXISTS old_spec JSONB;
ALTER TABLE bots DROP CONSTRAINT IF EXISTS bots_role;
ALTER TABLE bots ADD CONSTRAINT bots_role CHECK (role IN ('bot', 'orchestrator'));
CREATE UNIQUE INDEX IF NOT EXISTS bots_one_orchestrator ON bots (org_id) WHERE role = 'orchestrator';

ALTER TABLE bot_runs ADD COLUMN IF NOT EXISTS session_id TEXT DEFAULT '' NOT NULL;

CREATE TABLE IF NOT EXISTS bot_plugins (
    id UUID DEFAULT gen_random_uuid() NOT NULL,
    org_id UUID NOT NULL,
    bot_id UUID NOT NULL,
    name TEXT NOT NULL,
    version TEXT NOT NULL,
    source TEXT NOT NULL,
    files JSONB DEFAULT '{}'::jsonb NOT NULL,
    installed_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY(org_id) REFERENCES orgs (id) ON DELETE CASCADE,
    FOREIGN KEY(bot_id) REFERENCES bots (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS bot_plugins_one ON bot_plugins (bot_id, name);

CREATE TABLE IF NOT EXISTS bot_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    org_id UUID NOT NULL,
    run_id UUID NOT NULL,
    session_id TEXT NOT NULL,
    subpath TEXT DEFAULT '' NOT NULL,
    entry JSONB NOT NULL,
    PRIMARY KEY (id),
    FOREIGN KEY(org_id) REFERENCES orgs (id) ON DELETE CASCADE,
    FOREIGN KEY(run_id) REFERENCES bot_runs (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS bot_sessions_of_run ON bot_sessions (run_id, session_id, subpath, id);

ALTER TABLE bot_plugins ENABLE ROW LEVEL SECURITY;
ALTER TABLE bot_plugins FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant ON bot_plugins;
CREATE POLICY tenant ON bot_plugins USING (nullif(current_setting('glyphh.org_id', true), '') IS NULL OR org_id = nullif(current_setting('glyphh.org_id', true), '')::uuid);
ALTER TABLE bot_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE bot_sessions FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant ON bot_sessions;
CREATE POLICY tenant ON bot_sessions USING (nullif(current_setting('glyphh.org_id', true), '') IS NULL OR org_id = nullif(current_setting('glyphh.org_id', true), '')::uuid);
